// Build data/genera-index.js from data/genera/*.json.
//
// The catalogue grid needs each genus's reviewed record fields (period, age,
// description, facts, taxonomy…) and review status at page load, before any
// individual genus file is fetched. This script extracts just those fields so
// index.html can boot from one small file. Everything else (prose, evidence,
// presentation, sources) is fetched per genus from data/genera/<id>.json.
//
// Run:  node tools/build-genera-index.mjs
// The GitHub Action in .github/workflows/genera-index.yml runs it on every
// push that touches data/genera/, so hand edits made on GitHub stay in sync.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'data/genera';
const OUT = 'data/genera-index.js';
const KEEP = ['status', 'scientificDisposition', 'reviewedOn', 'record', 'ageReviewNote', 'residualUncertainty'];

const index = {};
const files = readdirSync(DIR).filter(f => f.endsWith('.json')).sort();
for (const file of files) {
  const genus = JSON.parse(readFileSync(join(DIR, file), 'utf8'));
  const id = file.replace(/\.json$/, '');
  if (genus.id !== id) throw new Error(`${file}: "id" is "${genus.id}", expected "${id}"`);
  const review = genus.review;
  if (!review) continue;
  const entry = {};
  for (const key of KEEP) if (review[key] !== undefined) entry[key] = review[key];
  entry.sourceUrls = (review.sources || []).map(s => s.url).filter(Boolean);
  index[id] = entry;
}

const banner = `/* AUTO-GENERATED by tools/build-genera-index.mjs — do not edit by hand.
   Catalogue-level review fields for ${Object.keys(index).length} genera, extracted from
   data/genera/*.json. Edit the genus file instead; this index is rebuilt by
   the genera-index GitHub Action on push. */\n`;
writeFileSync(OUT, `${banner}window.GENERA_INDEX = ${JSON.stringify(index)};\nwindow.SCIENTIFIC_REVIEWS = window.GENERA_INDEX;\n`);
console.log(`wrote ${OUT}: ${Object.keys(index).length} genera`);
